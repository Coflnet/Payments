-- Apply after 20261119211429_RenewalExtension and right before deploying "switch a running subscription to a longer term".
-- Run with the existing migration authority and stop on the first error.
-- In cockroach sql, enable \set errexit before reading/pasting this file.
-- Rerunnable after interruption; do not wrap the whole script in a transaction.
-- One new table (no backfill); the app user gets access to it and its identity sequence.

-- One row per switch of a running Stripe/PayPal subscription to a longer term (4 -> 13/52 weeks, 13 -> 52): the agreed price
-- charged now (ChargedCents, which the paying invoice must charge), the access end the new term is added to, the provider payment
-- that paid it (InvoiceId: granted once; its refund reverts exactly that grant) and, for PayPal, the new subscription that
-- replaces the old one (NewSubscriptionId).
CREATE TABLE IF NOT EXISTS "SubscriptionTermSwitches" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "SubscriptionId" character varying(64),
    "Provider" character varying(16),
    "UserId" character varying(64),
    "NewSubscriptionId" character varying(64),
    "PreviousProductId" integer,
    "ProductId" integer,
    "RenewalProductId" integer,
    "Weeks" integer NOT NULL,
    "RegularCents" bigint NOT NULL,
    "ChargedCents" bigint NOT NULL,
    "RenewalCents" bigint NOT NULL,
    "Currency" character varying(3),
    "PromotionCode" character varying(50),
    "AccessEndsBefore" timestamp with time zone NOT NULL,
    "InvoiceId" character varying(64),
    "PaymentUrl" character varying(1024),
    "PaymentRequestId" integer,
    "Status" character varying(16),
    "CreatedAt" timestamp with time zone NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "CompletedAt" timestamp with time zone,
    CONSTRAINT "PK_SubscriptionTermSwitches" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_SubscriptionTermSwitches_Product_PreviousProductId" FOREIGN KEY ("PreviousProductId") REFERENCES "Product" ("Id"),
    CONSTRAINT "FK_SubscriptionTermSwitches_Product_ProductId" FOREIGN KEY ("ProductId") REFERENCES "Product" ("Id"),
    CONSTRAINT "FK_SubscriptionTermSwitches_Product_RenewalProductId" FOREIGN KEY ("RenewalProductId") REFERENCES "Product" ("Id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_InvoiceId" ON "SubscriptionTermSwitches" ("InvoiceId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_NewSubscriptionId" ON "SubscriptionTermSwitches" ("NewSubscriptionId");
CREATE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_PreviousProductId" ON "SubscriptionTermSwitches" ("PreviousProductId");
CREATE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_ProductId" ON "SubscriptionTermSwitches" ("ProductId");
CREATE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_RenewalProductId" ON "SubscriptionTermSwitches" ("RenewalProductId");
CREATE INDEX IF NOT EXISTS "IX_SubscriptionTermSwitches_SubscriptionId_Status" ON "SubscriptionTermSwitches" ("SubscriptionId", "Status");

