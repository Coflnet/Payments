-- Apply after 20261022112747_PaymentRequestCoinAmount and before deploying direct Stripe/PayPal subscriptions.
-- Run with the existing migration authority and stop on the first error.
-- In cockroach sql, enable \set errexit before reading/pasting this file.
-- Rerunnable after interruption; do not wrap the whole script in a transaction.
--
-- DATA LOSS WARNING: the DELETE below removes older duplicate rows of a user's subscription and the EF Down()
-- migration can not restore them. Before running it, save the output of the preview SELECT (or back up the
-- "Subscriptions" table, e.g. CREATE TABLE "Subscriptions_backup_20261117" AS SELECT * FROM "Subscriptions";).
-- The script stops (a deliberately failing cast) if one provider subscription is recorded for different users;
-- resolve those rows by hand, then rerun.

ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "CreatorCode" character varying(50);
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "Currency" character varying(3);
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "DiscountCode" character varying(50);
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "ManagedPayments" boolean NOT NULL DEFAULT false;
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "PriceCents" bigint;
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "ProviderPlanId" character varying(64);
-- The buyer country of the checkout (VAT country of direct sales); the US direct subscription cap counts by it (together with CheckoutRegion below)
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "CheckoutCountry" character varying(2);
-- The buyer's state/province at checkout (ISO 3166-2 subdivision code without country prefix, from the edge); the US direct cap counts per state
ALTER TABLE "Subscriptions" ADD COLUMN IF NOT EXISTS "CheckoutRegion" character varying(3);
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "RecurringAmount" numeric;
-- The buyer country a subscription checkout was priced for (the VAT country of direct sales)
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "Country" character varying(2);
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "CheckoutRegion" character varying(3);
-- PayPal subscriptions: the codes of the checkout, copied to the subscription on activation
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "CreatorCode" character varying(50);
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "DiscountCode" character varying(50);
-- Subscription checkouts: sold through Stripe Managed Payments (not reused for a direct checkout of the same amount)
ALTER TABLE "PaymentRequests" ADD COLUMN IF NOT EXISTS "ManagedPayments" boolean NOT NULL DEFAULT false;

-- Place of supply evidence per payment (the IP address column already exists): the VAT country of the checkout,
-- Stripe: billing address country / PayPal: payer country, Stripe: card issuing country. Existing tables keep their grants.
ALTER TABLE "PaymentRecords" ADD COLUMN IF NOT EXISTS "CheckoutCountry" character varying(2);
ALTER TABLE "PaymentRecords" ADD COLUMN IF NOT EXISTS "BillingCountry" character varying(2);
ALTER TABLE "PaymentRecords" ADD COLUMN IF NOT EXISTS "PaymentMethodCountry" character varying(2);
-- Checkout state/province and (Stripe) billing address state as evidence for the per-state US cap; never used to reject a payment
ALTER TABLE "PaymentRecords" ADD COLUMN IF NOT EXISTS "CheckoutRegion" character varying(3);
ALTER TABLE "PaymentRecords" ADD COLUMN IF NOT EXISTS "BillingRegion" character varying(16);
-- The subscription checkout (PaymentRequest) an early performance declaration was given for
ALTER TABLE "ServicePerformanceDeclarations" ADD COLUMN IF NOT EXISTS "PaymentRequestId" integer;

CREATE TABLE IF NOT EXISTS "DiscountCodes" (
    -- INT4 explicitly: the model maps Id to a 32 bit integer (CockroachDB's plain INTEGER is 64 bit).
    "Id" INT4 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "Code" character varying(50) NOT NULL,
    "Name" character varying(100),
    "AmountType" character varying(10) NOT NULL,
    "Amount" numeric NOT NULL,
    -- JSON object of billing weeks to amount, e.g. {"4":25,"13":50,"52":50}
    "PeriodAmounts" text,
    "AutoApply" boolean NOT NULL,
    "IsActive" boolean NOT NULL,
    "SubscriptionOnly" boolean NOT NULL,
    "Duration" character varying(10),
    "MaxRedemptions" integer,
    "TimesRedeemed" integer NOT NULL,
    "StartsAt" timestamp with time zone,
    "ExpiresAt" timestamp with time zone,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_DiscountCodes" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_DiscountCodes_Code" ON "DiscountCodes" ("Code");

CREATE TABLE IF NOT EXISTS "PayPalPlans" (
    "Id" INT4 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "ProductSlug" character varying(100) NOT NULL,
    "BillingWeeks" integer NOT NULL,
    "Currency" character varying(3) NOT NULL,
    "PlanId" character varying(64) NOT NULL,
    "PayPalProductId" character varying(64),
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_PayPalPlans" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_PayPalPlans_ProductSlug_BillingWeeks_Currency" ON "PayPalPlans" ("ProductSlug", "BillingWeeks", "Currency");

-- Providers are compared as they are after the backfill below (NULL/'' = 'lemonsqueezy'), so duplicates are removed BEFORE the
-- backfill: the release running until this one ships still writes Lemon Squeezy rows without a provider, which the unique index
-- below does not catch (NULLs are distinct), and backfilling two of them for one subscription would violate it on a rerun.
-- Same comparison as the --preview of apply-direct-subscriptions.sh.

-- Stop if one provider subscription is recorded for different users (needs a human decision, never deleted here).
-- Returns no rows when there is none; otherwise the failing cast names the subscription in the error message.
SELECT CAST('STOP: subscription ' || coalesce(nullif(s."ProviderSlug", ''), 'lemonsqueezy') || ' ' || s."ExternalId" || ' is recorded for several users; resolve before migrating' AS INT8)
FROM "Subscriptions" s JOIN "Subscriptions" o
  ON coalesce(nullif(s."ProviderSlug", ''), 'lemonsqueezy') = coalesce(nullif(o."ProviderSlug", ''), 'lemonsqueezy')
 AND s."ExternalId" = o."ExternalId" AND s."UserId" <> o."UserId"
LIMIT 1;

-- Preview (save this output): the duplicated rows of a user's subscription the next statement removes.
SELECT s."Id", s."ProviderSlug", s."ExternalId", s."UserId", s."ProductId", s."Status", s."RenewsAt", s."EndsAt", s."UpdatedAt"
FROM "Subscriptions" s JOIN "Subscriptions" newer
  ON coalesce(nullif(s."ProviderSlug", ''), 'lemonsqueezy') = coalesce(nullif(newer."ProviderSlug", ''), 'lemonsqueezy')
 AND s."ExternalId" = newer."ExternalId" AND s."UserId" = newer."UserId"
 AND (s."UpdatedAt" < newer."UpdatedAt" OR (s."UpdatedAt" = newer."UpdatedAt" AND s."Id" < newer."Id"));

-- The subscription list already deleted such duplicates when it read them; keep the newest row.
DELETE FROM "Subscriptions" s USING "Subscriptions" newer
WHERE coalesce(nullif(s."ProviderSlug", ''), 'lemonsqueezy') = coalesce(nullif(newer."ProviderSlug", ''), 'lemonsqueezy')
  AND s."ExternalId" = newer."ExternalId" AND s."UserId" = newer."UserId"
  AND (s."UpdatedAt" < newer."UpdatedAt" OR (s."UpdatedAt" = newer."UpdatedAt" AND s."Id" < newer."Id"));

-- Rows written before providers were recorded are Lemon Squeezy subscriptions.
UPDATE "Subscriptions" SET "ProviderSlug" = 'lemonsqueezy' WHERE "ProviderSlug" IS NULL OR "ProviderSlug" = '';

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Subscriptions_ProviderSlug_ExternalId" ON "Subscriptions" ("ProviderSlug", "ExternalId");
-- Per-state counting of active direct US subscriptions (grouped by region). It replaces the (CheckoutCountry, Status) index
-- an earlier draft of this script created: drop that one in case such a draft already ran here.
DROP INDEX IF EXISTS "Subscriptions"@"IX_Subscriptions_CheckoutCountry_Status";
CREATE INDEX IF NOT EXISTS "IX_Subscriptions_CheckoutCountry_CheckoutRegion_Status" ON "Subscriptions" ("CheckoutCountry", "CheckoutRegion", "Status");

-- Concurrent refund webhooks must not both reverse a creator share: reversal rows ("<payment>#refund:<key>") are unique.
-- The index is partial on purpose. Reversal rows are new with this release, so none can be duplicated yet, but sale rows
-- written by earlier releases were never checked for duplicate TransactionReference values; a full unique index could
-- fail on them, and they must not be deleted (revenue rows are never removed silently).
-- Stop (failing cast) if reversal-like rows are already duplicated, e.g. by a half applied earlier attempt.
SELECT CAST('STOP: duplicate creator revenue reversal ' || "TransactionReference" || '; resolve by hand before migrating' AS INT8)
FROM "CreatorCodeRevenues" WHERE "TransactionReference" LIKE '%#refund:%'
GROUP BY "TransactionReference" HAVING count(*) > 1 LIMIT 1;
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CreatorCodeRevenues_Reversal" ON "CreatorCodeRevenues" ("TransactionReference")
WHERE "TransactionReference" LIKE '%#refund:%';

